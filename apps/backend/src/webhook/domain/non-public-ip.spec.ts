import { describe, expect, it } from "vitest";
import { isNonPublicIp } from "./non-public-ip.js";

describe("isNonPublicIp", () => {
    it.each([
        ["0.0.0.0", "this network"],
        ["10.0.0.5", "private"],
        ["100.64.0.1", "carrier-grade NAT"],
        ["127.0.0.1", "loopback"],
        ["169.254.169.254", "cloud metadata"],
        ["172.16.0.1", "private"],
        ["172.31.255.255", "private"],
        ["192.0.0.8", "IETF protocol assignments"],
        ["192.0.2.1", "documentation"],
        ["192.88.99.1", "6to4 relay anycast"],
        ["192.168.1.1", "private"],
        ["198.18.0.1", "benchmarking"],
        ["198.19.255.255", "benchmarking"],
        ["198.51.100.1", "documentation"],
        ["203.0.113.1", "documentation"],
        ["224.0.0.1", "multicast"],
        ["239.255.255.250", "multicast"],
        ["240.0.0.1", "reserved"],
        ["255.255.255.255", "broadcast"],
        ["::", "unspecified"],
        ["::1", "loopback"],
        ["::7f00:1", "IPv4-compatible"],
        ["::8.8.8.8", "IPv4-compatible, even with a public address"],
        ["::ffff:127.0.0.1", "IPv4-mapped loopback"],
        ["::ffff:7f00:1", "IPv4-mapped loopback, hex"],
        ["::ffff:127.0.0.1%eth0", "IPv4-mapped loopback with zone"],
        ["::ffff:a9fe:a9fe", "IPv4-mapped metadata"],
        ["::ffff:0:a00:5", "IPv4-translated"],
        ["64:ff9b::a00:5", "NAT64 to a private address"],
        ["64:ff9b::127.0.0.1", "NAT64 to loopback"],
        ["64:ff9b:1::a00:5", "local-use NAT64"],
        ["64:ff9b:1::808:808", "local-use NAT64 to a public address"],
        ["100::1", "discard-only"],
        ["2001::1", "Teredo"],
        ["2001:2::1", "benchmarking"],
        ["2001:db8::1", "documentation"],
        ["2002:a00:5::1", "6to4 of a private address"],
        ["2002:a9fe:a9fe::", "6to4 of the metadata address"],
        ["3fff::1", "documentation"],
        ["5f00::1", "SRv6 SID"],
        ["fc00::1", "unique local"],
        ["fd12:3456::1", "unique local"],
        ["fe80::1", "link-local"],
        ["fe80::1%lo0", "link-local with zone"],
        [
            "fe80:0000:0000:0000:0000:0000:255.255.255.255%lo0",
            "link-local, long form with zone",
        ],
        ["0:0:0:0:0:ffff:7f00:1", "IPv4-mapped loopback, uncompressed"],
        ["0:0:0:0:0:ffff:127.0.0.1", "IPv4-mapped loopback, uncompressed"],
        ["2001:1ff:ffff::1", "end of IETF protocol assignments"],
        ["fec0::1", "site-local"],
        ["ff02::1", "multicast"],
        ["not-an-ip", "no address"],
        ["", "empty"],
    ])("blocks %s (%s)", (address) => {
        expect(isNonPublicIp(address)).toBe(true);
    });

    it.each([
        ["8.8.8.8"],
        ["93.184.216.34"],
        ["172.15.255.255"],
        ["172.32.0.1"],
        ["100.63.255.255"],
        ["100.128.0.1"],
        ["198.17.255.255"],
        ["198.20.0.0"],
        ["223.255.255.255"],
        ["::ffff:8.8.8.8"],
        ["::ffff:808:808"],
        ["64:ff9b::808:808"],
        ["64:ff9b::8.8.8.8"],
        ["2002:808:808::1"],
        ["2001:4860:4860::8888"],
        ["2001:200::1"],
        ["2001:db9::1"],
        ["2a03:2880:f12f:83:face:b00c:0:25de"],
        ["2606:4700:4700::1111"],
        ["2a00:1450:4001:82a::200e"],
    ])("allows the public address %s", (address) => {
        expect(isNonPublicIp(address)).toBe(false);
    });
});
