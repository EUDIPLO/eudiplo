import { ApiPropertyOptional } from "@nestjs/swagger";
import { createZodDto } from "nestjs-zod";
import { z } from "zod";

export const IssuerRegistrationCertificateMode = {
    IMPORT: "import",
    GENERATE: "generate",
} as const;
export type IssuerRegistrationCertificateMode =
    (typeof IssuerRegistrationCertificateMode)[keyof typeof IssuerRegistrationCertificateMode];

const IssuerRegistrationCertificateConfigSchema = z
    .object({
        enabled: z.boolean().optional(),
        mode: z.enum(IssuerRegistrationCertificateMode).optional(),
        jwt: z.string().optional(),
        privacyPolicy: z.string().optional(),
        supportUri: z.string().optional(),
    })
    .strict();

const IssuerRegistrationCertificateCacheSchema = z
    .object({
        jwt: z.string(),
        fingerprint: z.string(),
        issuedAt: z.number().optional(),
        expiresAt: z.number().optional(),
    })
    .strict();

export class IssuerRegistrationCertificateConfig extends createZodDto(
    IssuerRegistrationCertificateConfigSchema,
) {
    @ApiPropertyOptional({
        description:
            "Enable inclusion of a registration certificate in credential issuer metadata.",
        default: false,
    })
    enabled?: boolean;

    @ApiPropertyOptional({
        enum: IssuerRegistrationCertificateMode,
        description:
            "import: use an existing JWT, generate: create via registrar using attestation data derived from configured credential configurations.",
        default: IssuerRegistrationCertificateMode.GENERATE,
    })
    mode?: IssuerRegistrationCertificateMode;

    @ApiPropertyOptional({
        description:
            "Existing registration certificate JWT used when mode is import.",
    })
    jwt?: string;

    @ApiPropertyOptional({
        description:
            "Privacy policy URL used when generating a registration certificate (optional if registrar defaults are configured).",
        example: "https://issuer.example/privacy",
    })
    privacyPolicy?: string;

    @ApiPropertyOptional({
        description:
            "Support URI used when generating a registration certificate (optional if registrar defaults are configured).",
        example: "mailto:support@issuer.example",
    })
    supportUri?: string;
}

export class IssuerRegistrationCertificateCache extends createZodDto(
    IssuerRegistrationCertificateCacheSchema,
) {
    @ApiPropertyOptional({
        description:
            "Cached registration certificate JWT generated by EUDIPLO.",
        readOnly: true,
    })
    jwt!: string;

    @ApiPropertyOptional({
        description: "Config fingerprint used to detect cache invalidation.",
        readOnly: true,
    })
    fingerprint!: string;

    @ApiPropertyOptional({
        description: "JWT iat claim, seconds since epoch.",
        readOnly: true,
    })
    issuedAt?: number;

    @ApiPropertyOptional({
        description: "JWT exp claim, seconds since epoch.",
        readOnly: true,
    })
    expiresAt?: number;
}
